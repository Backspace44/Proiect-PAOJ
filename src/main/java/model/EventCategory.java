package main.java.model;

/**
 * Enum representing different categories of events in the system.
 * Used to classify events for filtering and organizational purposes.
 */
public enum EventCategory {
    CONCERT,     // Musical performance event
    SPORTS,      // Athletic competition or sports-related event
    THEATER,     // Theatrical performance or play
    CINEMA,      // Film screening or movie-related event
    EXHIBITION,  // Art or product display event
    CONFERENCE,  // Professional or educational gathering
    FESTIVAL     // Cultural or celebration event
}